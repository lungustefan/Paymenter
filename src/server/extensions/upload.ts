import fs from 'node:fs';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { unzipSync } from 'fflate';

const ucfirst = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const entryOf = (dir: string) => ['index.ts', 'index.tsx', 'index.js'].map((f) => path.join(dir, f)).find((f) => fs.existsSync(f));

/** the dir that holds the extension's entry file (the zip may wrap it in one folder) */
function validateExtensionPath(dir: string, depth = 0): string {
    if (depth > 1) throw new Error('Maximum depth reached while validating extension path.');
    if (entryOf(dir)) return dir;
    for (const sub of fs.readdirSync(dir, { withFileTypes: true })) {
        if (!sub.isDirectory() || sub.name === '__MACOSX') continue;
        if (entryOf(path.join(dir, sub.name))) return validateExtensionPath(path.join(dir, sub.name), depth + 1);
    }
    throw new Error('No valid extension files found in the provided path.');
}

/** `class X extends Server | Gateway | Extension` of the entry file */
function getExtensionType(dir: string): { type: 'server' | 'gateway' | 'other'; class: string } {
    const source = fs.readFileSync(entryOf(dir)!, 'utf8');
    const m = /class\s+([A-Za-z_][A-Za-z0-9_]*)\s+extends\s+(Server|Gateway|Extension)\b/.exec(source);
    if (!m) throw new Error('No valid extension class found in the provided path.');
    return { class: m[1], type: m[2] === 'Server' ? 'server' : m[2] === 'Gateway' ? 'gateway' : 'other' };
}

/**
 * Port of `UploadExtensionService::handle`: unpacks the zip into `extensions/<Type>s/<Name>`.
 * The extension is bundled by Next.js, so it only becomes available after a rebuild / restart
 * (the registry is regenerated by `pnpm dev` / `pnpm build`).
 */
export function uploadExtension(zipPath: string): { type: 'server' | 'gateway' | 'other'; name: string; updated: boolean } {
    if (!fs.existsSync(zipPath)) throw new Error('File does not exist or is not readable.');
    if (path.extname(zipPath) !== '.zip') throw new Error('Invalid file type. Only zip files are allowed.');
    const extractPath = path.join(process.cwd(), 'storage', 'app', 'extensions', randomBytes(6).toString('hex'));
    fs.mkdirSync(extractPath, { recursive: true });
    try {
        let files: Record<string, Uint8Array>;
        try {
            files = unzipSync(new Uint8Array(fs.readFileSync(zipPath)));
        } catch {
            throw new Error('Failed to open the zip file.');
        }
        for (const [name, data] of Object.entries(files)) {
            const target = path.resolve(extractPath, name);
            if (target !== extractPath && !target.startsWith(extractPath + path.sep)) throw new Error('Invalid file path in the zip file.');
            if (name.endsWith('/')) fs.mkdirSync(target, { recursive: true });
            else {
                fs.mkdirSync(path.dirname(target), { recursive: true });
                fs.writeFileSync(target, data);
            }
        }
        fs.rmSync(zipPath, { force: true });
        const source = validateExtensionPath(extractPath);
        const info = getExtensionType(source);
        // the folder name is what the extension is loaded by
        const name = source === extractPath ? info.class : path.basename(source);
        const destination = path.join(process.cwd(), 'extensions', `${ucfirst(info.type)}s`, name);
        const updated = fs.existsSync(destination);
        if (updated) fs.rmSync(destination, { recursive: true, force: true });
        fs.cpSync(source, destination, { recursive: true });
        return { type: info.type, name, updated };
    } finally {
        fs.rmSync(extractPath, { recursive: true, force: true });
    }
}
