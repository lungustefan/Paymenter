#!/usr/bin/env node
/**
 * Builds src/admin/icons/heroicons.ts: the subset of Heroicons the admin panel uses
 * (`heroicon-o-*` outline, `-s-` solid, `-m-` mini, `-c-` micro - the same names Filament uses).
 * Reference `heroicon-<style>-<name>` anywhere in src/themes/extensions (or add it to
 * scripts/heroicons.txt) and re-run `node scripts/generate-heroicons.mjs`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'node_modules', 'heroicons');
const dirFor = { o: '24/outline', s: '24/solid', m: '20/solid', c: '16/solid' };

const names = new Set();
const listFile = path.join(root, 'scripts', 'heroicons.txt');
if (fs.existsSync(listFile)) for (const l of fs.readFileSync(listFile, 'utf8').split('\n')) if (l.trim() && !l.startsWith('#')) names.add(l.trim());

function scan(dir) {
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        if (['node_modules', '.next', 'generated'].includes(e.name)) continue;
        const p = path.join(dir, e.name);
        if (e.isDirectory()) scan(p);
        else if (/\.(tsx?|jsx?|json)$/.test(e.name) && !p.endsWith('heroicons.ts')) {
            for (const m of fs.readFileSync(p, 'utf8').matchAll(/\bheroicon-([osmc])-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(`heroicon-${m[1]}-${m[2]}`);
        }
    }
}
for (const d of ['src', 'themes', 'extensions']) scan(path.join(root, d));

const out = {};
for (const full of [...names].sort()) {
    const m = /^heroicon-([osmc])-(.+)$/.exec(full);
    const file = path.join(base, dirFor[m[1]], `${m[2]}.svg`);
    if (!fs.existsSync(file)) {
        console.warn(`[heroicons] missing ${full}`);
        continue;
    }
    const svg = fs.readFileSync(file, 'utf8').trim();
    const attrs = /<svg([^>]*)>/.exec(svg)[1];
    const inner = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>$/, '').replace(/\s*\n\s*/g, '');
    const attr = (n) => new RegExp(`${n}="([^"]*)"`).exec(attrs)?.[1];
    out[full] = { viewBox: attr('viewBox'), fill: attr('fill'), stroke: attr('stroke'), strokeWidth: attr('stroke-width'), inner };
}

const file = path.join(root, 'src', 'admin', 'icons', 'heroicons.ts');
fs.mkdirSync(path.dirname(file), { recursive: true });
fs.writeFileSync(
    file,
    `// AUTO-GENERATED by scripts/generate-heroicons.mjs - do not edit.\nexport interface HeroiconData { viewBox: string; fill?: string; stroke?: string; strokeWidth?: string; inner: string }\nexport const heroicons: Record<string, HeroiconData> = ${JSON.stringify(out, null, 4)};\n`,
);
console.log(`[heroicons] ${Object.keys(out).length} icons`);
