#!/usr/bin/env node
// Converts the payment brand SVGs of the PHP theme (components/icons/*.blade.php) into src/components/icons/payment-icons.ts
import fs from 'node:fs';
import path from 'node:path';

const src = process.argv[2] ?? '/home/user/ref/themes/default/views/components/icons';
const out = path.resolve('src/components/icons/payment-icons.ts');
const icons = {};
for (const file of fs.readdirSync(src).filter((f) => f.endsWith('.blade.php')).sort()) {
    const name = file.replace('.blade.php', '');
    const raw = fs.readFileSync(path.join(src, file), 'utf8').trim();
    const m = /^<svg\s+\{\{\s*\$attributes\s*\}\}([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(raw);
    if (!m) throw new Error(`unexpected markup in ${file}`);
    const attrs = Object.fromEntries([...m[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map((a) => [a[1], a[2]]));
    icons[name] = { attrs, inner: m[2].trim() };
}
fs.writeFileSync(out, `// AUTO-GENERATED by scripts/generate-payment-icons.mjs. Do not edit by hand.\nexport const paymentIcons: Record<string, { attrs: Record<string, string>; inner: string }> = ${JSON.stringify(icons, null, 4)};\n`);
console.log(`wrote ${Object.keys(icons).length} icons`);
