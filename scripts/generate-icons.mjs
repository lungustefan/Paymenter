#!/usr/bin/env node
/**
 * Builds src/components/icons/remix-icons.ts: the subset of Remix Icon used by
 * the app (the original used `andreiio/blade-remix-icon`). Add a name to
 * `extra` (or reference `ri-<name>` anywhere in src/themes/extensions) and re-run.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = path.join(root, 'node_modules', 'remixicon', 'icons');

// name -> svg inner markup, from every category folder
const all = new Map();
for (const cat of fs.readdirSync(iconsDir)) {
    const dir = path.join(iconsDir, cat);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir)) if (f.endsWith('.svg')) all.set(f.slice(0, -4), path.join(dir, f));
}

function scan(dir, names) {
    if (!fs.existsSync(dir)) return;
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
        if (e.name === 'node_modules' || e.name === '.next' || e.name === 'generated') continue;
        const p = path.join(dir, e.name);
        if (e.isDirectory()) scan(p, names);
        else if (/\.(tsx?|jsx?|json)$/.test(e.name) && !p.endsWith('remix-icons.ts')) {
            for (const m of fs.readFileSync(p, 'utf8').matchAll(/\bri-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(m[1]);
        }
    }
}

const names = new Set();
// icons carried over from the original theme + admin panel
const listFile = path.join(root, 'scripts', 'icons.txt');
if (fs.existsSync(listFile)) for (const l of fs.readFileSync(listFile, 'utf8').split('\n')) if (l.trim()) names.add(l.trim());
for (const d of ['src', 'themes', 'extensions']) scan(path.join(root, d), names);
// icons chosen at runtime (`ri-home-2` + `-fill`/`-line`) need both variants
const out = {};
for (const n of names) {
    for (const candidate of [n, `${n}-line`, `${n}-fill`]) {
        const file = all.get(candidate);
        if (file && !out[candidate]) {
            const svg = fs.readFileSync(file, 'utf8');
            const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<path fill="none" d="M0 0h24v24H0z"\/>/, '').trim();
            out[candidate] = inner;
        }
    }
}
const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
fs.writeFileSync(
    path.join(root, 'src', 'components', 'icons', 'remix-icons.ts'),
    `// AUTO-GENERATED by scripts/generate-icons.mjs (Remix Icon, Apache-2.0). Do not edit by hand.\nexport const remixIcons: Record<string, string> = ${JSON.stringify(sorted, null, 4)};\n`,
);
console.log(`[icons] ${Object.keys(sorted).length} icons`);
