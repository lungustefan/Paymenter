#!/usr/bin/env node
/**
 * Discovers themes and extensions on disk and writes src/generated/registry.ts.
 *
 * Like the PHP release, dropping a folder into ./themes or ./extensions is all
 * that is needed; a rebuild (`pnpm build`) registers it. Because the bundler
 * needs static import paths, discovery happens here at build time.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'src', 'generated', 'registry.ts');

const entryFiles = (dir, names) => names.map((n) => path.join(dir, n)).find((f) => fs.existsSync(f));
const dirs = (p) => (fs.existsSync(p) ? fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith('.')).map((d) => d.name).sort() : []);

const themes = [];
const themeModules = [];
for (const name of dirs(path.join(root, 'themes'))) {
    const dir = path.join(root, 'themes', name);
    if (entryFiles(dir, ['theme.ts', 'theme.tsx', 'theme.js'])) themes.push(name);
    // a theme with an index file provides the layout + page views
    if (entryFiles(dir, ['index.ts', 'index.tsx', 'index.js'])) themeModules.push(name);
}

const extensions = [];
for (const typeDir of dirs(path.join(root, 'extensions'))) {
    const type = typeDir.toLowerCase().replace(/s$/, '');
    for (const name of dirs(path.join(root, 'extensions', typeDir))) {
        const dir = path.join(root, 'extensions', typeDir, name);
        const entry = entryFiles(dir, ['index.ts', 'index.tsx', 'index.js']);
        if (entry) extensions.push({ typeDir, type, name });
    }
}

const lines = [
    '// AUTO-GENERATED by scripts/generate-registry.mjs - do not edit.',
    '// Re-generated on `pnpm dev` / `pnpm build`.',
    '',
    'export const themeRegistry: Record<string, () => Promise<any>> = {',
    ...themes.map((t) => `    ${JSON.stringify(t)}: () => import('@themes/${t}/theme'),`),
    '};',
    '',
    'export const themeModuleRegistry: Record<string, () => Promise<any>> = {',
    ...themeModules.map((t) => `    ${JSON.stringify(t)}: () => import('@themes/${t}'),`),
    '};',
    '',
    'export interface ExtensionEntry { type: string; name: string; dir: string; load: () => Promise<any>; }',
    'export const extensionRegistry: ExtensionEntry[] = [',
    ...extensions.map((e) => `    { type: ${JSON.stringify(e.type)}, name: ${JSON.stringify(e.name)}, dir: ${JSON.stringify(e.typeDir + '/' + e.name)}, load: () => import('@extensions/${e.typeDir}/${e.name}') },`),
    '];',
    '',
];

fs.mkdirSync(path.dirname(out), { recursive: true });
const next = lines.join('\n');
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== next) fs.writeFileSync(out, next);
console.log(`[registry] ${themes.length} theme(s), ${extensions.length} extension(s)`);
